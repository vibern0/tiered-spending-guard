// Build-only bridge: publish public compiler artifacts/configuration, never runtime capabilities.
const { createHash, randomUUID } = require('node:crypto');
const { copyFileSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync } = require('node:fs');
const { dirname, join, resolve } = require('node:path');

const RESOURCE_FILES = Object.freeze([
  'artifacts/contracts/TieredSpendingGuard.sol/TieredSpendingGuard.json',
  'artifacts/contracts/SafeAtomicSetupHelper.sol/SafeAtomicSetupHelper.json',
  'artifacts/contracts/GuardReplacementMaintenance.sol/GuardReplacementMaintenance.json',
  'config/sepolia.pwa-phase-one.json',
  'config/sepolia.pwa-provisioning-automation.json',
  'config/sepolia.pwa-provisioning-successor.json',
  'config/sepolia.pwa-provisioning-successor-1031.json',
  'config/sepolia.pwa-historical-vault.json',
  'config/artifacts/zodiac-delay-v1.1.1-mastercopies.json',
]);
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');

/** Enumerate compiler sources/build inputs in stable order; absent directories fail closed. */
function filesBelow(root, directory) {
  return readdirSync(join(root, directory), { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name)).flatMap(entry => {
    const name = `${directory}/${entry.name}`;
    return entry.isDirectory() ? filesBelow(root, name) : [name];
  });
}

/** Hash canonical build inputs, including imported compiler inputs in Hardhat build-info. */
function inputHashes(coreRoot) {
  const names = [...RESOURCE_FILES, ...filesBelow(coreRoot, 'contracts'), ...filesBelow(coreRoot, 'artifacts/build-info'),
    'hardhat.config.ts', 'package.json', 'scripts/sdk-resources.cjs', '../../pnpm-lock.yaml'];
  return Object.fromEntries([...new Set(names)].sort().map(name => [name, sha256(readFileSync(join(coreRoot, name)))]));
}

/** Invalidate consumable SDK output before a clean or new non-coverage compilation. */
function invalidateResources(sdkRoot) {
  rmSync(join(sdkRoot, 'generated'), { recursive: true, force: true });
}

/** Publish one complete deterministic resource set; failure leaves no consumable old output. */
function generateResources(coreRoot, sdkRoot) {
  if (process.env.SOLIDITY_COVERAGE === 'true') throw new Error('coverage cannot publish SDK resources');
  invalidateResources(sdkRoot);
  const temporary = join(sdkRoot, `.generated-${randomUUID()}.tmp`);
  try {
    const inputs = inputHashes(coreRoot);
    const resources = {};
    for (const file of RESOURCE_FILES) {
      const source = join(coreRoot, file);
      const bytes = readFileSync(source);
      JSON.parse(bytes.toString('utf8'));
      const target = join(temporary, file);
      mkdirSync(dirname(target), { recursive: true });
      copyFileSync(source, target);
      resources[file] = sha256(bytes);
    }
    const manifest = { formatVersion: 1, inputs, resources };
    writeFileSync(join(temporary, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
    renameSync(temporary, join(sdkRoot, 'generated'));
  } catch (error) {
    invalidateResources(sdkRoot);
    throw error;
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
}

/** Compare generated bytes and manifest against current build inputs; never repair implicitly. */
function verifyResources(coreRoot, sdkRoot) {
  const generated = join(sdkRoot, 'generated');
  const manifest = JSON.parse(readFileSync(join(generated, 'manifest.json'), 'utf8'));
  if (manifest.formatVersion !== 1 || JSON.stringify(manifest.inputs) !== JSON.stringify(inputHashes(coreRoot)) ||
      JSON.stringify(Object.keys(manifest.resources ?? {})) !== JSON.stringify(RESOURCE_FILES)) throw new Error('SDK resource inputs are stale; run core:build');
  for (const file of RESOURCE_FILES) {
    if (sha256(readFileSync(join(generated, file))) !== manifest.resources[file] || manifest.resources[file] !== manifest.inputs[file]) throw new Error('SDK generated resource integrity mismatch');
  }
}

module.exports = { RESOURCE_FILES, generateResources, verifyResources, invalidateResources };
if (require.main === module) {
  const coreRoot = resolve(__dirname, '..');
  const sdkRoot = resolve(coreRoot, '../sdk');
  const command = process.argv[2];
  if (command === 'generate') generateResources(coreRoot, sdkRoot);
  else if (command === 'check') verifyResources(coreRoot, sdkRoot);
  else if (command === 'clean') invalidateResources(sdkRoot);
  else throw new Error('expected generate, check, or clean');
}
